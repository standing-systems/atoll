// Builds atoll: the CLI as one ESM file (dist/atoll.mjs, also copied into both plugins), the library
// entry points (dist/index.mjs, dist/testing.mjs) with declarations, and the templates `atoll init` embeds.
// `node build.mjs --templates` regenerates only src/cli/templates.generated.ts.

import { chmodSync, copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const pkg = JSON.parse(readFileSync(join(here, "package.json"), "utf8"));

function filesUnder(root) {
  if (!existsSync(root)) return {};
  const out = {};
  for (const name of readdirSync(root, { recursive: true }).map(String).sort()) {
    if (/(^|\/)(node_modules|\.atoll-local|\.actord|\.DS_Store|package-lock\.json)(\/|$)/.test(name)) continue;
    const full = join(root, name);
    if (statSync(full).isFile()) out[name] = readFileSync(full, "utf8");
  }
  return out;
}

function generateTemplates() {
  const templates = { project: filesUnder(join(here, "templates", "project")) };
  for (const example of ["release-radar", "promise-keeper", "upgrade-steward"]) {
    const files = filesUnder(join(here, "examples", example));
    // An example's own package.json and tsconfig belong to this repository; the project template's apply.
    delete files["package.json"];
    delete files["tsconfig.json"];
    templates[example] = files;
  }
  const body = `// Generated by build.mjs from templates/project and examples/. Do not edit.\nexport const TEMPLATES: Record<string, Record<string, string>> = ${JSON.stringify(templates, null, 2)};\n`;
  writeFileSync(join(here, "src", "cli", "templates.generated.ts"), body);
  return templates;
}

generateTemplates();
if (process.argv.includes("--templates")) process.exit(0);

const { build } = await import("esbuild");
rmSync(join(here, "dist"), { recursive: true, force: true });

await build({
  entryPoints: [join(here, "src", "cli", "main.ts")],
  outfile: join(here, "dist", "atoll.mjs"),
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node22",
  banner: { js: "#!/usr/bin/env node\nimport { createRequire as __atollRequire } from 'node:module'; const require = __atollRequire(import.meta.url);" },
  define: { __ATOLL_VERSION__: JSON.stringify(pkg.version) },
  external: ["esbuild"],
  legalComments: "none",
  logLevel: "warning",
});
chmodSync(join(here, "dist", "atoll.mjs"), 0o755);

const library = { bundle: true, platform: "node", format: "esm", target: "node22", external: ["esbuild", "disk"], legalComments: "none", logLevel: "warning" };
await build({ ...library, entryPoints: [join(here, "src", "index.ts")], outfile: join(here, "dist", "index.mjs") });
await build({ ...library, entryPoints: [join(here, "src", "testing.ts")], outfile: join(here, "dist", "testing.mjs") });

execFileSync("npx", ["--no-install", "tsc", "-p", join(here, "tsconfig.build.json")], { cwd: here, stdio: "inherit" });
for (const file of readdirSync(join(here, "dist", "types"), { recursive: true }).map(String)) {
  if (!file.endsWith(".d.ts")) continue;
  const path = join(here, "dist", "types", file);
  writeFileSync(path, readFileSync(path, "utf8").replace(/(from\s+["']\.{1,2}\/[^"']+)\.ts(["'])/g, "$1.js$2"));
}

for (const host of ["claude", "codex"]) {
  const dist = join(here, "plugins", host, "dist");
  mkdirSync(dist, { recursive: true });
  copyFileSync(join(here, "dist", "atoll.mjs"), join(dist, "atoll.mjs"));
  chmodSync(join(dist, "atoll.mjs"), 0o755);
  writeFileSync(join(dist, "VERSION"), `${pkg.version}\n`);
}

const size = statSync(join(here, "dist", "atoll.mjs")).size;
console.log(`built atoll ${pkg.version}: dist/atoll.mjs (${(size / 1024).toFixed(0)} KiB), dist/index.mjs, dist/testing.mjs, dist/types; copied into ${["claude", "codex"].map((h) => relative(here, join(here, "plugins", h, "dist"))).join(" and ")}`);
